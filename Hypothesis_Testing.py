# calculating the two-tailed p_values... 
# importing norm from scipy.stats...
from scipy.stats import norm

# 18 days mean recovery with 1.5 std_dev
# value for mean...
mean = 18

# value for std_dev...
std_dev = 1.5

# probability of 16 pr less days... 
p1 = norm.cdf(16, mean, std_dev)

# probability of 20 or more days... 
