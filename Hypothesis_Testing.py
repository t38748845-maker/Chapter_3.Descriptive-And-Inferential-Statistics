# calculating the probability of recovery between 15 and 21 days...
# importing norm from scipy.stats...
from scipy.stats import norm

# 18 days mean recovery with 1.5 std_dev
# value for mean...
mean = 18

# value for std_dev...
std_dev = 1.5

# 95% probability recovery time takes between 15 to 21 days...
# using CDF...
x = norm.cdf(21, mean, std_dev) - norm.cdf(15, mean, std_dev)

# prints x...
print(x)



